function initMagneticEffects() {
  const shouldSkip =
    !window.matchMedia ||
    window.matchMedia("(prefers-reduced-motion: reduce)").matches ||
    !window.matchMedia("(hover: hover) and (pointer: fine)").matches;

  if (shouldSkip) {
    return;
  }

  const magneticTargets = document.querySelectorAll(".btn, .btn-secondary, .site-nav a, .project-link, .course-link, .back-link");
  magneticTargets.forEach((element) => element.classList.add("magnetic-target"));

  let rafId = 0;
  let activeTarget = null;
  let nextX = 0;
  let nextY = 0;

  const animate = () => {
    if (!activeTarget) {
      rafId = 0;
      return;
    }

    activeTarget.style.transform = `translate3d(${nextX}px, ${nextY}px, 0)`;
    rafId = requestAnimationFrame(animate);
  };

  magneticTargets.forEach((target) => {
    target.addEventListener("mousemove", (event) => {
      const rect = target.getBoundingClientRect();
      const relX = event.clientX - rect.left - rect.width / 2;
      const relY = event.clientY - rect.top - rect.height / 2;
      nextX = relX * 0.12;
      nextY = relY * 0.12;
      activeTarget = target;
      if (!rafId) {
        rafId = requestAnimationFrame(animate);
      }
    });

    target.addEventListener("mouseleave", () => {
      target.style.transform = "";
      activeTarget = null;
      nextX = 0;
      nextY = 0;
      if (rafId) {
        cancelAnimationFrame(rafId);
        rafId = 0;
      }
    });
  });
}

function initHeroRuntime(config) {
  if (!config || !config.canvas) {
    return;
  }

  const { canvas, mode } = config;
  const context = canvas.getContext("2d", { alpha: true });
  if (!context) {
    return;
  }

  const drawPlaceholder = () => {
    const rect = canvas.getBoundingClientRect();
    const dpr = window.devicePixelRatio || 1;
    canvas.width = Math.floor(rect.width * dpr);
    canvas.height = Math.floor(rect.height * dpr);
    context.setTransform(dpr, 0, 0, dpr, 0, 0);

    const gradient = context.createLinearGradient(0, 0, rect.width, rect.height);
    gradient.addColorStop(0, "#DBEAFE");
    gradient.addColorStop(1, "#CCFBF1");
    context.fillStyle = gradient;
    context.fillRect(0, 0, rect.width, rect.height);

    context.fillStyle = "rgba(37,99,235,0.2)";
    context.beginPath();
    context.arc(rect.width * 0.22, rect.height * 0.28, rect.width * 0.18, 0, Math.PI * 2);
    context.fill();

    context.fillStyle = "rgba(20,184,166,0.23)";
    context.beginPath();
    context.arc(rect.width * 0.76, rect.height * 0.72, rect.width * 0.2, 0, Math.PI * 2);
    context.fill();

    context.fillStyle = "#0F172A";
    context.font = "600 14px Segoe UI";
    context.fillText(`Canvas ready (${mode})`, 14, rect.height - 16);
  };

  drawPlaceholder();
  window.addEventListener("resize", drawPlaceholder);

  /*
    Runtime integration hook:
    - Rive: init here with the same `canvas` instance
    - Spline runtime: mount and render scene here
  */
}

