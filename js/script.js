function initScrollAnimations() {
  const shouldSkip =
    !window.IntersectionObserver ||
    (window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches);

  if (shouldSkip) {
    return;
  }

  const targets = document.querySelectorAll(".surface-card, .project-card, .panel, .course-card");
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.14 });

  targets.forEach((target) => {
    target.classList.add("reveal-on-scroll");
    observer.observe(target);
  });
}

function initDynamicGradients() {
  const gradientTargets = document.querySelectorAll(".hero-visual, .course-detail-hero, .course-hero");
  const shouldSkip =
    !gradientTargets.length ||
    !window.matchMedia ||
    window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  if (shouldSkip) {
    return;
  }

  gradientTargets.forEach((target) => {
    target.addEventListener("pointermove", (event) => {
      const rect = target.getBoundingClientRect();
      const x = Math.round(((event.clientX - rect.left) / rect.width) * 100);
      const y = Math.round(((event.clientY - rect.top) / rect.height) * 100);
      target.style.setProperty("--pointer-x", `${x}%`);
      target.style.setProperty("--pointer-y", `${y}%`);
    });
  });
}

function initReducedMotionHandling() {
  if (!window.matchMedia) {
    return;
  }

  const motionQuery = window.matchMedia("(prefers-reduced-motion: reduce)");
  const applyMotionPreference = () => {
    document.documentElement.classList.toggle("reduced-motion", motionQuery.matches);
  };

  applyMotionPreference();
  motionQuery.addEventListener("change", applyMotionPreference);
}

function initCourseFilters() {
  const search = document.getElementById("course-search");
  const cards = Array.from(document.querySelectorAll("[data-course-card]"));
  const filters = Array.from(document.querySelectorAll("[data-course-filter]"));
  const emptyState = document.querySelector("[data-course-empty]");

  if (!cards.length) {
    return;
  }

  let activeFilter = "all";
  const normalize = (value) => value.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");

  const applyFilters = () => {
    const query = normalize(search ? search.value.trim() : "");
    let visibleCount = 0;

    cards.forEach((card) => {
      const title = normalize(card.dataset.title || "");
      const category = card.dataset.category || "";
      const matchesSearch = !query || title.includes(query) || normalize(category).includes(query);
      const matchesFilter = activeFilter === "all" || category === activeFilter;
      const isVisible = matchesSearch && matchesFilter;
      card.hidden = !isVisible;
      if (isVisible) {
        visibleCount += 1;
      }
    });

    if (emptyState) {
      emptyState.hidden = visibleCount !== 0;
    }
  };

  if (search) {
    search.addEventListener("input", applyFilters);
  }

  filters.forEach((filter) => {
    filter.addEventListener("click", () => {
      activeFilter = filter.dataset.courseFilter || "all";
      filters.forEach((item) => item.classList.toggle("active", item === filter));
      applyFilters();
    });
  });
}

